import {
  ResponsiveContainer,
  BarChart,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
} from "recharts";

import {
  Card,
  CardContent,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";

const formatCurrency = (value) =>
  `₹${Number(value || 0).toLocaleString("en-IN")}`;

const BranchSalesChart = ({ data = [] }) => {
  return (
    <Card>
      <CardHeader>
        <CardTitle>Branch Performance</CardTitle>

        <p className="text-sm text-muted-foreground">
          Sales generated by each branch.
        </p>
      </CardHeader>

      <CardContent>
        {data.length === 0 ? (
          <div className="flex h-[300px] items-center justify-center text-sm text-muted-foreground">
            No branch sales data available.
          </div>
        ) : (
          <div className="h-[300px] w-full">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart
                data={data}
                layout="vertical"
                margin={{
                  top: 10,
                  right: 20,
                  left: 20,
                  bottom: 5,
                }}
              >
                <CartesianGrid strokeDasharray="3 3" />

                <XAxis
                  type="number"
                  tick={{ fontSize: 12 }}
                  tickFormatter={formatCurrency}
                />

                <YAxis
                  type="category"
                  dataKey="branchName"
                  width={100}
                  tick={{ fontSize: 12 }}
                />

                <Tooltip
                  formatter={(value) => [
                    formatCurrency(value),
                    "Sales",
                  ]}
                />

                <Bar
                  dataKey="totalSales"
                  fill="currentColor"
                  className="text-primary"
                  radius={[0, 4, 4, 0]}
                />
              </BarChart>
            </ResponsiveContainer>
          </div>
        )}
      </CardContent>
    </Card>
  );
};

export default BranchSalesChart;